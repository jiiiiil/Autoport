/**
 * Keeps the downloadable/exported code 1:1 identical to the live preview.
 *
 * Reads the REAL source of the 3d-creator portfolio renderer and its static
 * cover assets, then emits them as TypeScript constants that both the
 * client-side code viewer (code-generator.ts) can embed without drift.
 *
 * Run automatically before `dev` and `build` (see package.json).
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = process.cwd();
const RENDERER_PATH = join(ROOT, "src/components/portfolio/creator3d-portfolio-renderer.tsx");
const COVERS_DIR = join(ROOT, "public/covers");
const OUT_DIR = join(ROOT, "src/lib/portfolio/generated");

mkdirSync(OUT_DIR, { recursive: true });

const header = "// AUTO-GENERATED by scripts/sync-creator3d.mjs — DO NOT EDIT MANUALLY.\n// Regenerated from src/components/portfolio/creator3d-portfolio-renderer.tsx + public/covers on every dev/build.\n";

const source = readFileSync(RENDERER_PATH, "utf8");
writeFileSync(
  join(OUT_DIR, "creator3d-source.ts"),
  header +
    'export const CREATOR3D_RENDERER_FILENAME = "creator3d-portfolio-renderer.tsx";\n' +
    "export const CREATOR3D_SOURCE = " +
    JSON.stringify(source) +
    ";\n"
);

let coverCount = 0;
try {
  const covers = readdirSync(COVERS_DIR)
    .filter((f) => f.endsWith(".svg"))
    .sort()
    .map((f) => ({
      path: "public/covers/" + f,
      content: readFileSync(join(COVERS_DIR, f), "utf8"),
    }));
  coverCount = covers.length;
  writeFileSync(
    join(OUT_DIR, "creator3d-assets.ts"),
    header +
      "export interface Creator3dAssetFile {\n  path: string;\n  content: string;\n}\n\n" +
      "export const CREATOR3D_ASSET_FILES: Creator3dAssetFile[] = " +
      JSON.stringify(covers, null, 2) +
      ";\n"
  );
} catch {
  writeFileSync(
    join(OUT_DIR, "creator3d-assets.ts"),
    header + "export interface Creator3dAssetFile {\n  path: string;\n  content: string;\n}\n\nexport const CREATOR3D_ASSET_FILES: Creator3dAssetFile[] = [];\n"
  );
}

console.log(`[sync-creator3d] renderer source synced (${source.length} chars), ${coverCount} cover assets synced.`);
